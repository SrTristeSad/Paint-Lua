-- Smoke test puro: nao exige janela nem imagens do LOVE.
package.path=package.path..""
local Model=require("src.model")
local Bridge=require("app.paint_bridge")
local model=Model.new()
model:open_gallery()
model:open_new_canvas()
model:create_canvas(64,48)
local bridge=Bridge.new()
local doc=assert(bridge:sync(model))
assert(doc.w==64 and doc.h==48 and #doc.layers==1)
model:add_layer()
doc=assert(bridge:sync(model))
assert(#doc.layers==2 and doc.sel==2)
model:toggle_layer_visibility(model.active_layer_id)
bridge:sync(model)
assert(doc.layers[2].visible==false)
assert(#doc.history.undo==2, "adicionar/visibilidade devem registrar histórico")
bridge:sync(model)
assert(#doc.history.undo==2, "redesenho não deve criar histórico")
local id=model.active_layer_id
model:toggle_layer_clipping(id)
bridge:sync(model)
assert(doc.layers[2].clipped and #doc.history.undo==3, "clipping real/histórico")
model:set_layer_blending(id,"Multiply")
bridge:sync(model)
assert(doc.layers[2].blend=="multiply" and #doc.history.undo==4, "blending real/histórico")
model:set_layer_opacity(id,45)
bridge:sync(model)
assert(doc.layers[2].opacity==45 and #doc.history.undo==4, "slider sem histórico por frame")
assert(bridge:historyStep(model,false), "undo blending")
bridge:sync(model)
assert(doc.layers[2].blend=="normal" and model:active_layer().blending=="Normal",
  "undo deve atualizar a interface")
assert(bridge:historyStep(model,true),"redo blending")
bridge:sync(model)
assert(doc.layers[2].blend=="multiply" and model:active_layer().blending=="Multiply",
  "redo deve atualizar a interface")
print("Bridge Ibis-Lua + Paint-Lua: smoke OK")
