-- v0.30: prévia transforma o PNG usando a geometria do motor v0.24.
return function(check)
  local Doc=require('core.doc')
  local Hist=require('core.history')
  local Import=require('src.png_import')
  local d=Doc.new(40,40,'PNG preview')
  local source=love.image.newImageData(2,2)
  source:setPixel(0,0,0.6,0.1,0.9,0.5)
  source:setPixel(1,1,0.2,0.8,0.1,1)
  local before=#d.history.undo
  local session=Import.preview(d,source,'teste.png')
  check('v0.30: prévia não cria camada',#d.layers==2 and #d.history.undo==before)
  check('v0.30: começa no centro do canvas',session.x==19 and session.y==19)
  check('v0.30: prévia compartilha geometria da transformação',Import.bounds(session).w==2)
  Import.adjust(session,6,3,2)
  check('v0.30: move e redimensiona a prévia',session.dx==6 and session.dy==3 and session.scaleX==2)
  check('v0.30: ajuste não toca histórico',#d.layers==2 and #d.history.undo==before)
  local layer,count=Import.insert(d,source,'teste.png',session)
  check('v0.30: confirmar cria uma camada',layer and #d.layers==3 and count>0)
  check('v0.30: importação registra uma única ação',#d.history.undo==before+1)
  check('v0.30: pixels não caem na posição antiga',select(4,layer.tiles['0,0']:getPixel(19,19))==0)
  check('v0.30: pixels chegam na nova posição',select(4,layer.tiles['0,0']:getPixel(25,22))>0)
  Hist.undo(d)
  check('v0.30: undo remove PNG deslocado',#d.layers==2)
  Hist.redo(d)
  check('v0.30: redo preserva PNG deslocado',d.layers[3]==layer)
  local other=Doc.new(40,40,'cancelamento')
  local cancelled=Import.preview(other,source,'cancel.png')
  Import.adjust(cancelled,0,0,1,math.pi/2)
  check('v0.30: rotação altera a área prevista',Import.bounds(cancelled).w>1.9)
  Import.cancel(cancelled)
  check('v0.30: cancelar não altera a pilha',#other.layers==2 and #other.history.undo==0)
  local blocked,reason=Import.insert(other,source,'cancel.png',cancelled)
  check('v0.30: sessão cancelada não pode ser aplicada',not blocked and reason)
  local far=Import.preview(other,source,'fora.png')
  Import.adjust(far,5000,0)
  local distant=Import.insert(other,source,'fora.png',far)
  check('v0.30: PNG fora do canvas não altera obra',not distant and #other.history.undo==0)
  local giant=Doc.new(2000,2000,'memoria')
  local src=love.image.newImageData(1400,1400)
  local tooBig=Import.preview(giant,src,'grande.png')
  Import.adjust(tooBig,0,0,2)
  local changed,why=Import.insert(giant,src,'grande.png',tooBig)
  check('v0.30: limite do raster impede RAM excessiva',not changed and why and #giant.history.undo==0)
end
