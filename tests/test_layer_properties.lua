package.path = "./?.lua;./?/init.lua;" .. package.path
local Model=require("src.model")
local s=Model.new()
s:open_gallery();s:open_new_canvas();s:create_canvas(1024,768)
local id=s.active_layer_id
local l=s:active_layer()
assert(l.opacity==100 and l.blending=="Normal")
assert(not l.clipping and not l.alpha_lock and not l.locked)
assert(s.background_mode=="white")
s:set_layer_opacity(id,42.5)
assert(l.opacity==43)
s:set_layer_opacity(id,0)
assert(l.opacity==0)
s:set_layer_opacity(id,100)
s:set_layer_blending(id,"Multiply")
assert(l.blending=="Multiply")
s:set_layer_blending(id,"Screen")
assert(l.blending=="Screen")
assert(s:toggle_layer_clipping(id))
assert(not s:toggle_layer_clipping(id))
assert(s:toggle_layer_alpha_lock(id))
assert(s:toggle_layer_lock(id))
s:rename_layer(id,"Layer A")
assert(l.name=="Layer A")
s:set_background("transparent_light")
assert(s.background_mode=="transparent_light")
s:set_background("transparent_dark")
assert(s.background_mode=="transparent_dark")
s:set_background("white")
assert(s.background_mode=="white")
local function invalid(fn) assert(not pcall(fn)) end
invalid(function() s:set_layer_opacity(id,-1) end)
invalid(function() s:set_layer_opacity(id,101) end)
invalid(function() s:set_layer_opacity(id,0/0) end)
invalid(function() s:set_layer_blending(id,"Unknown") end)
invalid(function() s:rename_layer(id,"") end)
invalid(function() s:set_background("magenta") end)
invalid(function() s:get_layer(9999) end)
assert(s:add_layer()==2)
assert(s:active_layer().opacity==100)
assert(s:active_layer().blending=="Normal")
assert(not s:active_layer().clipping)
print("PASS: propriedades das camadas, blending simulado, fundo e validações")
