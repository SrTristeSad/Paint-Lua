package.path="./?.lua;./?/init.lua;"..package.path
local G=require("src.gallery")
local g=G.new()
assert(g.current_folder==0 and #g:items()==0 and g:total_artworks()==0)
local folder=g:add_folder("Sketches")
local piece=g:add_artwork(1800,2400,"Study")
assert(folder==1 and piece==2 and g:total_artworks()==1)
assert(#g:folders()==2 and g:folders()[1].id==0)
assert(#g:items()==2)
assert(g:get(piece).width==1800 and g:get(piece).simulated)
assert(g:enter(folder)=="Sketches")
local nested=g:add_folder("2026")
local nested_art=g:add_artwork(900,600)
assert(#g:items()==2 and #g:items(0)==2)
assert(g:total_artworks()==2)
assert(g:enter(nested)=="2026")
assert(#g:items()==0)
assert(g:back() and g.current_folder==folder)
assert(g:back() and g.current_folder==0)
assert(not g:back())
g:rename(folder,"Drafts")
assert(g:get(folder).name=="Drafts")
assert(g:get(piece).parent==0)
g:move(piece,nested)
assert(g:get(piece).parent==nested)
assert(not pcall(function() g:move(folder,nested) end))
assert(not pcall(function() g:move(folder,folder) end))
assert(g:get(folder).parent==0)
g:enter(folder)
local p1=g:add_artwork(1024,1024,"A")
local p2=g:add_artwork(1280,720,"B")
assert(g:select(p1) and g:select(p2))
assert(#g:selection()==2)
assert(g:move_selection(0)==2)
assert(#g:selection()==0 and #g:items()==2 and #g:items(0)==3)
assert(g:get(p1).parent==0 and g:get(p2).parent==0)
g:clear_selection()
local original=g:get(folder)
original.name="tampered"
assert(g:get(folder).name=="Drafts")
assert(not pcall(function() g:add_folder(" ") end))
assert(not pcall(function() g:add_artwork(0,1) end))
assert(not pcall(function() g:rename(1234,"a") end))
assert(not pcall(function() g:enter(piece) end))
assert(not pcall(function() g:move(999,0) end))
assert(not pcall(function() g:select(p1) end))
-- No partial moves when one selected folder would become its own ancestor.
g:select(nested)
assert(not pcall(function() g:move_selection(nested) end))
assert(g:get(nested).parent==folder)
print("PASS: Gallery model (nested folders, simulated works, rename, move, selection)")
