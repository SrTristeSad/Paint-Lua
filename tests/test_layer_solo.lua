package.path = "./?.lua;./?/init.lua;" .. package.path
local Model = require("src.model")
local s=Model.new()
s:open_gallery();s:open_new_canvas();s:create_canvas(800,600)
local first=s.active_layer_id
local second=s:add_layer()
local third=s:add_layer()
s:toggle_layer_visibility(second)
assert(not s.layers[2].visible)
assert(s:toggle_layer_solo(first)==true)
assert(s.solo_layer_id==first)
assert(s.layers[1].visible and not s.layers[2].visible and not s.layers[3].visible)
assert(s:toggle_layer_solo(third)==true)
assert(not s.layers[1].visible and not s.layers[2].visible and s.layers[3].visible)
assert(s:toggle_layer_solo(third)==false)
assert(s.solo_layer_id==nil and s.solo_before==nil)
assert(s.layers[1].visible and not s.layers[2].visible and s.layers[3].visible)
assert(s:toggle_layer_solo(first))
assert(s:toggle_layer_visibility(third)==false)
assert(s.solo_layer_id==nil)
assert(s.layers[1].visible and not s.layers[2].visible and not s.layers[3].visible)
assert(s:toggle_layer_solo(first))
local new=s:add_layer()
assert(s.solo_layer_id==nil and new==4 and #s.layers==4)
local ok=pcall(function() s:toggle_layer_solo(9999) end)
assert(not ok)
print("PASS: layer solo (exclusividade, troca, restauração, visibilidade)")
